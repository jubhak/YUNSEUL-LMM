def script_sentences(limit: int = RECOMMENDED_SENTENCES) -> list:
    return SENTENCES[:max(1, min(int(limit), len(SENTENCES)))]


def read_text(limit: int = RECOMMENDED_SENTENCES) -> str:
    """대본 전체를 한 파일 분량의 텍스트로."""
    lines = ["# 내 목소리 학습 대본", ""]
    for s in script_sentences(limit):
        lines.append(f"{s['id']:02d}. {s['text']}")
        lines.append(f"    → {s['pitch']} / {s['tone']} / {s['tip']}")
        lines.append("")
    lines.append("## 녹음 팁")
    for t in RECORD_TIPS:
        lines.append(f"- {t}")
    return "\n".join(lines)
